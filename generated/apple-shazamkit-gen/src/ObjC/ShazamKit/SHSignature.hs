-- | The @SHSignature@ class is an opaque data container that can be used to store recognition data.
--
-- Signatures are a compact lossy representation of the original audio. The original audio cannot be recreated from a Signature, there exists only enough data to confirm that the signature matches a certain piece of audio when it is also converted into a Signature. It is similar in utility to a hashing function.
--
-- Signatures can be matched against any type of audio not just music. The only requirement for a match is that the reference and query Signatures both contain the exact same pre recorded audio e.g. a live rendition of a song will not match against a studio recorded performance of the same piece.
--
-- There are exceptions to the requirement for exactly matching audio, a signature is robust against slight changes in frequency and speed.
--
-- Note: @SHSignature@ is not intended to be subclassed
--
-- Generated bindings for @SHSignature@.
module ObjC.ShazamKit.SHSignature
  ( SHSignature
  , IsSHSignature(..)
  , signatureWithDataRepresentation_error
  , initWithDataRepresentation_error
  , duration
  , dataRepresentation
  , dataRepresentationSelector
  , durationSelector
  , initWithDataRepresentation_errorSelector
  , signatureWithDataRepresentation_errorSelector


  ) where

import Foreign.Ptr (Ptr, FunPtr)
import Foreign.C.Types

import ObjC.Runtime.Types
import ObjC.Runtime.Message (sendMessage, sendOwnedMessage, sendClassMessage, sendOwnedClassMessage)
import ObjC.Runtime.Selector (mkSelector)
import ObjC.Runtime.Class (getRequiredClass)

import ObjC.ShazamKit.Internal.Classes
import ObjC.Foundation.Internal.Classes

-- | Create a Signature from Signature data
--
-- @dataRepresentation@ — Signature data generated by Shazam, this is not raw audio data
--
-- @error@ — Error if the data was invalid
--
-- Returns: A signature if the data contained a valid signature, nil otherwise
--
-- ObjC selector: @+ signatureWithDataRepresentation:error:@
signatureWithDataRepresentation_error :: (IsNSData dataRepresentation, IsNSError error_) => dataRepresentation -> error_ -> IO (Id SHSignature)
signatureWithDataRepresentation_error dataRepresentation error_ =
  do
    cls' <- getRequiredClass "SHSignature"
    sendClassMessage cls' signatureWithDataRepresentation_errorSelector (toNSData dataRepresentation) (toNSError error_)

-- | Create a Signature from Signature data
--
-- @dataRepresentation@ — Signature data generated by Shazam, this is not raw audio data
--
-- @error@ — Error if the data was invalid
--
-- Returns: A signature if the data contained a valid signature, nil otherwise
--
-- ObjC selector: @- initWithDataRepresentation:error:@
initWithDataRepresentation_error :: (IsSHSignature shSignature, IsNSData dataRepresentation, IsNSError error_) => shSignature -> dataRepresentation -> error_ -> IO (Id SHSignature)
initWithDataRepresentation_error shSignature dataRepresentation error_ =
  sendOwnedMessage shSignature initWithDataRepresentation_errorSelector (toNSData dataRepresentation) (toNSError error_)

-- | The duration of the input audio that this signature is derived from
--
-- The duration may not match the source audio duration exactly, audio that contains portions of silence may report shorter durations
--
-- ObjC selector: @- duration@
duration :: IsSHSignature shSignature => shSignature -> IO CDouble
duration shSignature =
  sendMessage shSignature durationSelector

-- | The raw data that comprises this signature, this is not audio data
--
-- ObjC selector: @- dataRepresentation@
dataRepresentation :: IsSHSignature shSignature => shSignature -> IO (Id NSData)
dataRepresentation shSignature =
  sendMessage shSignature dataRepresentationSelector

